AUDIENCE_SHEETS = [("Client", "Client Questions"), ("Internal Technical", "Internal Technical"),
                   ("Document Request", "Document Requests"),
                   ("Management Decision", "Management Decisions")]
PRIORITY_RANK = {"Critical": 0, "Important": 1, "Optional": 2}
CATEGORY_RANK = {"Business & Functional": 0, "Technical": 1, "Project Delivery": 2,
                 "Commercial & Contractual": 3}
PM_REC_LABELS = [("scope_reduction", "Reducing scope complexity"),
                 ("reuse", "Component reuse opportunities"),
                 ("deferrable", "Features that may be deferred"),
                 ("mvp", "Potential MVP"),
                 ("architecture_discussions", "Architecture discussions"),
                 ("risks", "Technical and delivery risks"),
                 ("management_issues", "Issues requiring management decisions"),
                 ("discussion_strategy", "Meeting / discussion strategy")]


def _q_sorted(qs):
    return sorted(qs, key=lambda q: (PRIORITY_RANK.get(q["priority"], 9),
                                     CATEGORY_RANK.get(q.get("category"), 9), q.get("topic", ""),
                                     q["id"]))


def clarifications(state, config, path, client_copy_path=None):
    wb = _new_wb()
    _cover(wb, config, state, "Client Clarifications & Discussion Points",
           "INTERNAL — red tabs must not be shared; send the CLIENT COPY instead")
    headers = ["Question ID", "Category", "Clarification Question", "Why It Matters",
               "Potential Impact", "Priority", "Related Requirements", "Status", "Topic",
               "Answer", "Answer Source"]
    fill = lambda row: PRIORITY_FILL.get(row[5]) if row[7] in ("Open", "Sent") else None  # noqa: E731
    for audience, title in AUDIENCE_SHEETS:
        qs = _q_sorted(q for q in state["clarifications"] if q["audience"] == audience)
        rows = [[q["id"], q["category"], q["question"], q.get("why"), q.get("impact"), q["priority"],
                 q.get("requirements", []), q["status"], q.get("topic"), q.get("answer"),
                 q.get("answer_source")] for q in qs]
        ws = sheet(wb, title, headers, rows, config,
                   widths=[10, 20, 60, 40, 34, 10, 16, 10, 18, 40, 20],
                   internal=audience != "Client", fills=fill)
        if rows:
            dv = DataValidation(type="list", formula1='"Open,Sent,Answered,Closed,Withdrawn"')
            ws.add_data_validation(dv)
            dv.add(f"H2:H{len(rows) + 1}")
    rec = state.get("pm_recommendations") or {}
    rec_rows = []
    for key, label in PM_REC_LABELS:
        for item in rec.get(key, []) or []:
            rec_rows.append([label, item if isinstance(item, str) else item.get("text", str(item))])
    for key, items in rec.items():
        if key not in dict(PM_REC_LABELS):
            for item in items or []:
                rec_rows.append([key.replace("_", " ").title(), str(item)])
    sheet(wb, "PM Recommendations", ["Area", "Recommendation & Discussion Strategy (INTERNAL)"],
          rec_rows, config, widths=[34, 110], internal=True)
    sum_rows = []
    for i, (audience, title) in enumerate(AUDIENCE_SHEETS, 2):
        n = max(sum(1 for q in state["clarifications"] if q["audience"] == audience) + 1, 2)
        r = f"'{title}'!$F$2:$F${n}"
        s = f"'{title}'!$H$2:$H${n}"
        sum_rows.append([title] + [Formula(f'=COUNTIF({r},"{p}")') for p in PRIORITY_RANK] +
                        [Formula(f'=COUNTIFS({r},"Critical",{s},"Open")+COUNTIFS({r},"Critical",{s},"Sent")'),
                         Formula(f"=COUNTA('{title}'!$A$2:$A${n})")])
    sheet(wb, "Summary", ["Register", "Critical", "Important", "Optional", "Critical Unresolved", "Total"],
          sum_rows, config, filters=False)
    wb.save(path)
    if client_copy_path:
        _client_copy(state, config, client_copy_path)


