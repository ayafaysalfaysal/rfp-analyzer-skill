class Formula(str):
    """Marks a string as a trusted formula generated by this module."""


PRIORITY_FILL = {"Critical": "F8CBAD", "Important": "FFE699", "Optional": "E2EFDA"}
STATUS_FILL = {"GAP": "F8CBAD", "Traced (provisional)": "FFE699", "Traced": "E2EFDA"}


def _require():
    if Workbook is None:
        raise RfpError("openpyxl is required for Excel output: pip install openpyxl. "
                       "Fallback: run `rfp.py export-csv` for CSV versions of the tables.")


def _new_wb():
    _require()
    wb = Workbook()
    wb.remove(wb.active)
    return wb


def _val(v):
    if isinstance(v, Formula):
        return str(v)
    if isinstance(v, (list, tuple, set)):
        return ", ".join(str(x) for x in v)
    if isinstance(v, bool):
        return "Yes" if v else "No"
    if v is None:
        return ""
    return v


def _style_header(ws, ncols, color):
    border = Side(style="thin", color="BFBFBF")
    for c in range(1, ncols + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=color)
        cell.alignment = Alignment(wrap_text=True, vertical="center")
        cell.border = Border(bottom=border)
    ws.row_dimensions[1].height = 30


def sheet(wb, title, headers, rows, config, widths=None, internal=False, numeric=(),
          fills=None, filters=True):
    """Write a formatted table. Untrusted strings starting with '=' are forced to text."""
    ws = wb.create_sheet(title[:31])
    color = (config.get("company") or {}).get("primary_color", "1F3864")
    for c, h in enumerate(headers, 1):
        ws.cell(row=1, column=c, value=h)
    _style_header(ws, len(headers), color)
    wrap = Alignment(wrap_text=True, vertical="top")
    for r, row in enumerate(rows, 2):
        for c, v in enumerate(row, 1):
            value = _val(v)
            cell = ws.cell(row=r, column=c, value=value)
            if isinstance(value, str) and value[:1] in ("=", "+", "-", "@") and not isinstance(v, Formula):
                cell.data_type = "s"  # formula-injection guard for client-supplied text
            cell.alignment = wrap
            if c in numeric:
                cell.number_format = "0.0#"
        if fills:
            color_hex = fills(row)
            if color_hex:
                for c in range(1, len(headers) + 1):
                    ws.cell(row=r, column=c).fill = PatternFill("solid", fgColor=color_hex)
    for c, h in enumerate(headers, 1):
        if widths and c <= len(widths) and widths[c - 1]:
            w = widths[c - 1]
        else:
            longest = max([len(str(h))] + [len(str(_val(row[c - 1]))) for row in rows[:200]
                                           if c - 1 < len(row)])
            w = min(max(10, longest + 2), 60)
        ws.column_dimensions[get_column_letter(c)].width = w
    ws.freeze_panes = "A2"
    if filters and rows:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows) + 1}"
    if internal:
        ws.sheet_properties.tabColor = "C00000"
    return ws


def _info_sheet(wb, title, pairs, config, internal=False):
    ws = sheet(wb, title, ["Item", "Value"], pairs, config, widths=[34, 100], internal=internal,
               filters=False)
    return ws


def _cover(wb, config, state, title, audience):
    pairs = [("Document", title), ("Project", state["project"].get("name") or "(not set)"),
             ("Client", state["project"].get("client") or "(not set)"),
             ("Prepared by", (config.get("company") or {}).get("name", "")),
             ("Audience", audience), ("Generated", now_iso()),
             ("Project status", state["project"].get("status")),
             ("Baseline version", state["project"].get("baseline_version") or "none")]
    return _info_sheet(wb, "About", pairs, config, internal=audience.startswith("INTERNAL"))


def _src(state, r):
    docs = {d["id"]: d for d in state["documents"]}
    out = []
    for s in r.get("sources", []):
        d = docs.get(s.get("doc"), {})
        loc = s.get("location", "")
        out.append(f"{s.get('doc')} {loc} ({d.get('name', '')})".replace("  ", " ").strip())
    return "; ".join(out)


