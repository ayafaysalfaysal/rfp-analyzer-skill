def change_register(state, config, path):
    wb = _new_wb()
    _cover(wb, config, state, "Change Impact Register", "INTERNAL")

    def prev(c):
        item = c["previous_state"].get(c["target"], {})
        base = item.get("description", "(new requirement)") if c["target"] != "NEW" else "(new requirement)"
        return f"{base} | effort {c['effort_before']['total_md']} MD total project"

    def proposed(c):
        req = (c["spec"].get("requirement") or {})
        parts = [f"{k}: {v}" for k, v in req.items() if k not in ("id", "key")]
        return f"{'; '.join(parts) or c['description']} | effort {c['effort_after']['total_md']} MD"

    rows = [[c["id"], c["target"] if c["target"] != "NEW" else c.get("created_requirement", "NEW"),
             prev(c), proposed(c), c["affected_requirements"],
             f"{'+' if c['effort_delta_md'] >= 0 else ''}{fmt_num(c['effort_delta_md'])} MD",
             f"{'+' if c['timeline_delta_days'] >= 0 else ''}{fmt_num(c['timeline_delta_days'])} working days",
             c["sow_sections"] or "None", c["approval_status"], c["description"],
             "Yes" if c["material"] else "No", c.get("decided_by"), c.get("decision"),
             c["assumptions_invalidated"] + [f"review {a}" for a in c["assumptions_to_review"]]]
            for c in state["changes"]]
    sheet(wb, "Impact Register",
          ["Change ID", "Changed Item", "Previous State", "Proposed State", "Affected Requirements",
           "Effort Impact", "Timeline Impact", "SOW Impact", "Approval Status", "Change Description",
           "Material", "Decided By", "Decision", "Assumptions Affected"], rows, config,
          widths=[10, 12, 45, 45, 18, 14, 18, 30, 12, 45, 9, 16, 10, 26],
          fills=lambda r: {"Pending": "FFE699", "Approved": "E2EFDA", "Rejected": "D9D9D9"}.get(r[8]))
    detail = []
    for c in state["changes"]:
        for w in c["wbs_changes"]:
            detail.append([c["id"], w["wbs"], w["action"], w["before_md"], w["after_md"], w["delta_md"]])
    sheet(wb, "WBS Effort Changes", ["Change ID", "WBS ID", "Action", "Before MD", "After MD", "Delta MD"],
          detail, config, numeric=(4, 5, 6))
    ms = [[c["id"], m["phase"], m["shift_days"], m["milestones"]]
          for c in state["changes"] for m in c["milestone_shift"]]
    sheet(wb, "Milestone Impact", ["Change ID", "Phase", "Shift (working days)", "Milestones"], ms, config)
    sheet(wb, "Summaries", ["Change ID", "Summary"], [[c["id"], c["summary"]] for c in state["changes"]],
          config, widths=[10, 140])
    wb.save(path)
