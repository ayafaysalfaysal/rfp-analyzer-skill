def requirements_matrix(state, config, path):
    wb = _new_wb()
    _cover(wb, config, state, "Requirements Matrix", "INTERNAL — review before sharing")
    q_by_req = {}
    for q in state["clarifications"]:
        for rid in q.get("requirements", []):
            q_by_req.setdefault(rid, []).append(q["id"])
    headers = ["Requirement ID", "Module", "Requirement Description", "Requirement Type", "Priority",
               "Source Reference", "Status", "Clarification Required", "Classification",
               "Priority Basis", "Scope", "Phase", "Interpretation / Notes", "Related Questions"]
    rows = []
    for r in state["requirements"]:
        rows.append([r["id"], r["module"], r["description"], r.get("type"),
                     r.get("priority"), _src(state, r), r.get("status"),
                     r.get("clarification_required"), r.get("classification"),
                     "Client-stated" if r.get("priority_source") == "Client"
                     else "Proposed (not confirmed by client)",
                     r.get("scope"), r.get("phase"),
                     " ".join(x for x in (r.get("interpretation"), r.get("notes")) if x),
                     q_by_req.get(r["id"], [])])
    ws = sheet(wb, "Requirements", headers, rows, config,
               widths=[12, 18, 60, 18, 10, 30, 11, 12, 18, 18, 12, 10, 40, 16])
    n = len(rows) + 1
    if rows:
        for col, opts in (("G", "Open,Confirmed,Changed,Removed"),
                          ("K", "In Scope,Out of Scope,Deferred")):
            dv = DataValidation(type="list", formula1=f'"{opts}"', allow_blank=True)
            ws.add_data_validation(dv)
            dv.add(f"{col}2:{col}{n}")
    modules = sorted({r["module"] for r in state["requirements"]})
    classes = ["Mandatory", "Optional", "Proposed Improvement", "Assumption", "Clarification Needed"]
    sum_rows = []
    rng = lambda col: f"Requirements!${col}$2:${col}${max(n, 2)}"  # noqa: E731
    for i, m in enumerate(modules, 2):
        row = [m, Formula(f"=COUNTIF({rng('B')},$A{i})")]
        for c in classes:
            row.append(Formula(f'=COUNTIFS({rng("B")},$A{i},{rng("I")},"{c}")'))
        row.append(Formula(f'=COUNTIFS({rng("B")},$A{i},{rng("K")},"In Scope")'))
        row.append(Formula(f'=COUNTIFS({rng("B")},$A{i},{rng("H")},"Yes")'))
        sum_rows.append(row)
    last = len(modules) + 1
    total = ["TOTAL"] + [Formula(f"=SUM({get_column_letter(c)}2:{get_column_letter(c)}{last})")
                         for c in range(2, 3 + len(classes) + 2)]
    sheet(wb, "Summary by Module", ["Module", "Total"] + classes + ["In Scope", "Need Clarification"],
          sum_rows + [total], config, filters=False)
    types = sorted({r.get("type") for r in state["requirements"]})
    sheet(wb, "Summary by Type", ["Requirement Type", "Count"],
          [[t, Formula(f"=COUNTIF({rng('D')},$A{i})")] for i, t in enumerate(types, 2)], config,
          filters=False)
    sheet(wb, "Source Documents",
          ["Doc ID", "Path", "Format", "Role", "Status", "Pages", "Duplicate Of", "Notes"],
          [[d["id"], d["path"], d.get("format"), d.get("role"), d["status"], d.get("pages"),
            d.get("duplicate_of"), d.get("notes")] for d in state["documents"]], config,
          widths=[9, 45, 8, 18, 16, 7, 12, 70])
    sheet(wb, "Missing References", ["Reference", "Referenced In", "Status", "Notes"],
          [[m.get("reference"), m.get("referenced_in"), m.get("status"), m.get("notes")]
           for m in state.get("missing_documents", [])], config, widths=[22, 24, 14, 70])
    _info_sheet(wb, "Legend", [
        ("Classification", "Mandatory / Optional (as stated by the RFP), Proposed Improvement "
                           "(our suggestion), Assumption (our assumption, not a client requirement), "
                           "Clarification Needed (cannot be scoped until clarified)"),
        ("Priority Basis", "Client-stated priorities are cited from the RFP. 'Proposed' priorities "
                           "are our recommendation and must be confirmed by the client."),
        ("Scope", "In Scope / Out of Scope / Deferred (later phase or separate engagement)"),
        ("IDs", "REQ IDs are stable across revisions; removed requirements keep their ID with "
                "status 'Removed'."),
    ], config)
    wb.save(path)


